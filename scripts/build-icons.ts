/**
 * Builds the "nif-icons" icon font from the SVGs in src/icons/ and writes a LESS
 * file (with the font embedded as a base64 WOFF) to src/styles/generated/nif-icons.less.
 *
 * For each icon `foo.svg` this generates a `.nif-icon-foo()` mixin and a matching
 * `.nif-icon-foo` class, mirroring what grunt-webfont used to produce.
 *
 * Run with `bun run icons` (it also runs automatically before `dev` and `build`).
 */
import { SVGIcons2SVGFontStream } from 'svgicons2svgfont';
import svg2ttf from 'svg2ttf';
import ttf2woff from 'ttf2woff';
import fs from 'node:fs';
import path from 'node:path';
import { Readable } from 'node:stream';

const root = path.resolve(import.meta.dirname, '..');
const iconsDir = path.join(root, 'src/icons');
const outFile = path.join(root, 'src/styles/generated/nif-icons.less');

const FONT_NAME = 'nif-icons';
const BASE_CLASS = 'nif-icon';
const START_CODEPOINT = 0xf101;

const files = fs
  .readdirSync(iconsDir)
  .filter((f) => f.endsWith('.svg'))
  .sort();

const glyphs = files.map((file, i) => ({
  file,
  name: path.basename(file, '.svg'),
  codepoint: START_CODEPOINT + i,
}));

const svgFont = await new Promise<string>((resolve, reject) => {
  const stream = new SVGIcons2SVGFontStream({
    fontName: FONT_NAME,
    fontHeight: 512,
    descent: 64,
    normalize: true,
  });
  let font = '';
  stream.on('data', (chunk: Buffer) => (font += chunk.toString()));
  stream.on('end', () => resolve(font));
  stream.on('error', reject);
  for (const glyph of glyphs) {
    // Strip the XML declaration - some of the (old Illustrator) SVGs declare an encoding
    // which the parser refuses to accept.
    const svg = fs.readFileSync(path.join(iconsDir, glyph.file), 'latin1').replace(/<\?xml[^>]*\?>/, '');
    const s = Readable.from([svg]) as Readable & { metadata: { name: string; unicode: string[] } };
    s.metadata = { name: glyph.name, unicode: [String.fromCodePoint(glyph.codepoint)] };
    stream.write(s);
  }
  stream.end();
});

const ttf = svg2ttf(svgFont, {});
const woff = ttf2woff(new Uint8Array(ttf.buffer));
const woffBase64 = Buffer.from(woff.buffer).toString('base64');

const less = `// Generated by scripts/build-icons.ts - do not edit by hand.

@font-face {
  font-family: "${FONT_NAME}";
  src: url("data:application/font-woff;charset=utf-8;base64,${woffBase64}") format("woff");
  font-weight: normal;
  font-style: normal;
}

.${BASE_CLASS} {
  display: inline-block;
  font-family: "${FONT_NAME}";
  font-style: normal;
  font-weight: normal;
  line-height: 1;
  speak: none;
  text-decoration: inherit;
  text-transform: none;
  text-rendering: optimizeLegibility;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

/* Icons */
${glyphs
  .map(
    ({ name, codepoint }) => `.${BASE_CLASS}-${name}() {
  &:before {
    content: "\\${codepoint.toString(16)}";
  }
}
.${BASE_CLASS}-${name} {
  .${BASE_CLASS}-${name}();
}`,
  )
  .join('\n')}
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, less);
console.log(`Built ${glyphs.length} icons into ${path.relative(root, outFile)}`);
